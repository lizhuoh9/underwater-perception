"""Export a post-hoc threshold variant of a locked ESP-DL CNN run and score it on TEST.

The variant re-applies the locked run's own calibration rule (optimize_pixel_forest.
constrained_threshold on the hashed int8 calibration curves) with a stricter FNR cap.
It is chosen after the locked TEST evaluation was seen, so its TEST numbers are not
an independent test; the locked evaluation stays the reported result. The model and
operator list are byte-identical to the locked export; only the header's threshold
code and the self-test frame's expected mask change.
"""

import argparse
import csv
import json
import re
import shutil
from pathlib import Path

import numpy as np
import torch

from uwseg.cnn_seg import int8_scores, load_work_frame, model_frame
from uwseg.compare_cnn_espdl import (
    BASELINES,
    COUNT_KEYS,
    SUBSETS,
    baseline_rows,
    check_lock_values,
    compare,
    sha,
    summarise,
    verify_graph,
)
from uwseg.optimize_pixel_forest import constrained_threshold
from uwseg.paths import DATA_DIR, REPO_ROOT, RESULTS_DIR, resolve
from uwseg.pixel_forest import score_image
from uwseg.train_cnn_espdl import device_codes, write_test_frame
from uwseg.udcp import confusion, metrics
from uwseg.validate import at_native_resolution, dump_json, load_sample

CLASS_NAMES = ["water", "diver", "plants", "wreck", "robot", "reef", "fish", "seafloor_rocks"]
# Changed after run_01 was locked only in write_header's float-literal formatting. verify_graph()
# replays the locked calibration counts through device_codes, proving the shared scoring path.
SOURCES_CHECKED_BY_REPLAY = {"train_cnn_espdl.py"}
LABELS = {
    "cnn_int8_variant": "CNN int8，事后阈值版本",
    "cnn_int8": "CNN int8，锁定阈值",
    "udcp_otsu_rgb565": "UDCP-Otsu RGB565",
    "forest_original": "原森林，阈值 57",
    "forest_threshold_only": "原森林，阈值 71（推荐）",
    "forest_lowfp": "16×8 森林，阈值 72",
}


def load_locked_run(run: Path, baseline: Path) -> tuple[dict, dict, dict, dict]:
    locked = json.loads((run / "LOCKED.json").read_text(encoding="utf-8"))
    plan = json.loads((run / "experiment_plan.json").read_text(encoding="utf-8"))
    if sha(run / "experiment_plan.json") != locked["plan_sha256"]:
        raise ValueError("Experiment plan changed after locking")
    for name, digest in locked["artifact_sha256"].items():
        if sha(run / name) != digest:
            raise ValueError(f"Locked artifact changed: {name}")
    changed = {
        name: {"locked": digest, "current": sha(resolve(name))}
        for name, digest in locked["source_sha256"].items()
        if sha(resolve(name)) != digest
    }
    if set(changed) - SOURCES_CHECKED_BY_REPLAY:
        raise ValueError(f"Source changed since locking: {sorted(set(changed) - SOURCES_CHECKED_BY_REPLAY)}")
    for name, digest in plan["inputs_sha256"].items():
        if sha(resolve(name)) != digest:
            raise ValueError(f"Input changed since training: {name}")
    audit_path = REPO_ROOT / plan["dedup_manifest"]["path"]
    if sha(audit_path) != plan["dedup_manifest"]["sha256"]:
        raise ValueError("Near-duplicate audit changed since training")
    evaluation = json.loads((run / "evaluation/summary.json").read_text(encoding="utf-8"))
    if evaluation["locked_sha256"] != sha(run / "LOCKED.json"):
        raise ValueError("The locked evaluation belongs to another lock")
    if (
        json.loads((baseline / "summary.json").read_text(encoding="utf-8"))["dedup_manifest_sha256"]
        != plan["dedup_manifest"]["sha256"]
    ):
        raise ValueError("Baseline evaluation used a different near-duplicate audit")
    check_lock_values(run, locked, plan)
    return locked, plan, json.loads(audit_path.read_text(encoding="utf-8")), changed


def variant_header(locked_header: str, locked_code: int, code: int, run_name: str, cap: float) -> str:
    stamp = "// Generated by train_cnn_espdl.py together with water_seg.espdl; keep them paired.\n"
    line = f"constexpr int kThresholdCode = {locked_code};"
    if locked_header.count(stamp) != 1 or locked_header.count(line) != 1:
        raise ValueError("Locked header layout not recognised")
    return locked_header.replace(
        stamp,
        f"// Post-hoc threshold variant of {run_name} (calibration FNR cap {cap:.0%}), chosen after\n"
        f"// its locked TEST evaluation; see MODEL_EXPORT.json. Otherwise identical to the locked header.\n",
    ).replace(line, f"constexpr int kThresholdCode = {code};")


def frame_pixels(header: str) -> str:
    return re.search(r"kTestFrameRgb565\[\d+\] = \{([^}]*)\}", header).group(1)


def run(run_dir: Path, baseline: Path, cap: float, output: Path) -> dict:
    if output.exists() and any(output.iterdir()):
        raise FileExistsError("Refusing to overwrite an export; choose a fresh --output")
    locked, plan, audit, changed = load_locked_run(run_dir, baseline)
    curves = json.loads((run_dir / "calibration_curves.json").read_text(encoding="utf-8"))["int8"]
    choice = constrained_threshold(np.array(curves["counts"]), np.array(curves["macro_image_miou"]), cap)
    locked_q, variant_q = locked["chosen"]["threshold_q"], choice["threshold_q"]
    from esp_ppq import TorchExecutor
    from esp_ppq.api import load_native_graph

    graph = load_native_graph(str(run_dir / "water_seg_native"))
    executor = TorchExecutor(graph=graph, device="cpu")
    original = json.loads((DATA_DIR / "manifest.json").read_text(encoding="utf-8"))
    calibration = [row for row in original["samples"] if row["split"] == "calibration"]
    samples = [row for row in original["samples"] if row["split"] == "test"]
    verify_graph(graph, executor, locked, calibration)
    mean, std = (np.array(locked[key], dtype=np.float32) for key in ("mean", "std"))

    def int8_score(sample):
        work, labels = load_work_frame(sample, REPO_ROOT)
        frame = model_frame(work)
        codes = device_codes(frame[None], mean, std, locked["input_exponent"])
        with torch.no_grad():
            quant = executor.forward(
                inputs=torch.from_numpy(codes.astype(np.float32)) * 2.0 ** locked["input_exponent"]
            )[0]
        return frame, labels, int8_scores(quant, locked["output_exponent"])[0]

    forest_export = json.loads(
        (RESULTS_DIR / "forest_lowfp/threshold_control/MODEL_EXPORT.json").read_text(encoding="utf-8")
    )
    forest_path = RESULTS_DIR / "forest_lowfp/threshold_control/model/pixel_forest_model.json"
    if sha(forest_path) != forest_export["exported_json_sha256"]:
        raise ValueError("Forest threshold-control model changed")
    forest_model, forest_q = json.loads(forest_path.read_text(encoding="utf-8")), forest_export["threshold_q"]
    with (run_dir / "evaluation/per_image.csv").open(encoding="utf-8") as handle:
        recorded = {
            row["id"]: [int(row[key]) for key in COUNT_KEYS]
            for row in csv.DictReader(handle)
            if row["method"] == "cnn_int8"
        }
    rows = baseline_rows(baseline, audit)
    baseline_counts = {(row["id"], row["method"]): [row[key] for key in COUNT_KEYS] for row in rows}
    strict = set(audit["test_subsets"]["without_same_scene"])
    per_class = {
        name: np.zeros((len(CLASS_NAMES), 2), dtype=np.int64)
        for name in ("cnn_int8_variant", "cnn_int8", "forest_threshold_only")
    }
    for index, sample in enumerate(samples, 1):
        _, labels, scores = int8_score(sample)
        rgb, _ = load_sample(sample)
        masks = {
            "cnn_int8": scores >= locked_q,
            "cnn_int8_variant": scores >= variant_q,
            "forest_threshold_only": score_image(rgb, forest_model) >= forest_q,
        }
        for name, mask in masks.items():
            native = at_native_resolution(mask.astype(np.uint8), labels).astype(bool)
            counts = list(confusion(native, labels != 0))
            reference = recorded[sample["id"]] if name == "cnn_int8" else baseline_counts.get((sample["id"], name))
            if reference is not None and counts != reference:
                raise AssertionError(f"{name} on {sample['id']} does not reproduce the recorded counts")
            if name != "forest_threshold_only":
                rows.append({"id": sample["id"], "method": name, **metrics(counts)})
            if sample["id"] in strict:
                for class_id in range(len(CLASS_NAMES)):
                    selected = labels == class_id
                    per_class[name][class_id] += [np.count_nonzero(native[selected]), np.count_nonzero(selected)]
        if index % 20 == 0:
            print(f"Scored {index}/{len(samples)} TEST images; recorded counts reproduced", flush=True)

    model_dir = output / "model"
    model_dir.mkdir(parents=True)
    for name in ("water_seg.espdl", "water_seg.compile_req.yml"):
        shutil.copyfile(run_dir / name, model_dir / name)
    locked_header = (run_dir / "water_seg_model_config.h").read_text(encoding="utf-8")
    (model_dir / "water_seg_model_config.h").write_text(
        variant_header(locked_header, locked_q - 128, variant_q - 128, run_dir.name, cap), encoding="utf-8"
    )
    test_sample = next(row for row in calibration if row["id"] == locked["test_frame_id"])
    frame, _, scores = int8_score(test_sample)
    write_test_frame(
        model_dir / "water_seg_test_frame.h", frame, (scores >= variant_q).astype(np.uint8), test_sample["id"]
    )
    if frame_pixels((model_dir / "water_seg_test_frame.h").read_text(encoding="utf-8")) != frame_pixels(
        (run_dir / "water_seg_test_frame.h").read_text(encoding="utf-8")
    ):
        raise AssertionError("Variant self-test frame differs from the locked frame")

    methods = ("cnn_int8_variant", "cnn_int8", *BASELINES)
    results = {
        name: {
            "images": len(audit["test_subsets"][name]),
            "methods": summarise(rows, audit["test_subsets"][name], methods),
            "variant_vs_forest_71": compare(
                rows, audit["test_subsets"][name], "cnn_int8_variant", "forest_threshold_only"
            ),
            "variant_vs_locked": compare(rows, audit["test_subsets"][name], "cnn_int8_variant", "cnn_int8"),
        }
        for name in SUBSETS
    }
    recall = {
        name: {CLASS_NAMES[c]: float(hits / total) for c, (hits, total) in enumerate(table) if total}
        for name, table in per_class.items()
    }
    export = {
        "policy": f"Post-hoc threshold variant: the locked run's calibration rule re-applied with FNR cap {cap}, "
        "chosen after the locked TEST evaluation was seen. Its TEST numbers are not an independent test; "
        f"{run_dir.name}/evaluation remains the reported result.",
        "source_run": run_dir.name,
        "fnr_cap": cap,
        "threshold_q": variant_q,
        "threshold_code": variant_q - 128,
        "locked_threshold_code": locked_q - 128,
        "calibration": choice,
        "locked_sha256": sha(run_dir / "LOCKED.json"),
        "locked_evaluation_summary_sha256": sha(run_dir / "evaluation/summary.json"),
        "byte_identical_to_locked": {
            name: sha(model_dir / name) for name in ("water_seg.espdl", "water_seg.compile_req.yml")
        },
        "header_sha256": sha(model_dir / "water_seg_model_config.h"),
        "test_frame_sha256": sha(model_dir / "water_seg_test_frame.h"),
        "sources_changed_since_lock": changed,
        "checks": "Locked artifacts, inputs, audit and lock values verified; calibration replay reproduced the locked counts; "
        "locked CNN and forest-71 per-image TEST counts reproduced exactly; self-test frame pixels equal the locked frame.",
    }
    dump_json(output / "MODEL_EXPORT.json", export)
    evaluation = output / "evaluation"
    evaluation.mkdir()
    with (evaluation / "per_image.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    summary = {
        "post_hoc": True,
        "subsets": results,
        "strict_subset_class_rates": recall,
        "export_sha256": sha(output / "MODEL_EXPORT.json"),
        "source_sha256": {
            name: sha(resolve(name))
            for name in ("export_cnn_threshold_variant.py", "compare_cnn_espdl.py", "cnn_seg.py")
        },
    }
    write_report(evaluation, summary, export)
    dump_json(evaluation / "summary.json", summary)
    return summary


def write_report(output: Path, summary: dict, export: dict) -> None:
    cal = export["calibration"]
    lines = [
        f"# 事后阈值版本：阈值码 {export['threshold_code']:+d}（标定漏检上限 {export['fnr_cap']:.0%}）",
        "",
        f"**这是看过锁定结果之后才选定的版本，下面的 TEST 数字不是独立检验。** 正式结果仍是锁定阈值码 "
        f"{export['locked_threshold_code']:+d} 的[锁定评估](../../evaluation/RESULTS.md)。",
        "规则与锁定版相同（标定集上取漏检不超过上限、误检最低的阈值），只把上限从 7.88% 降到 "
        f"{export['fnr_cap']:.0%}，以减少用于避障时漏掉的非水体。模型与算子清单与锁定版逐字节相同，只改阈值。",
        "",
        f"标定集：漏检 {cal['calibration_fnr']:.2%}，误检 {cal['calibration_fpr']:.2%}。",
        "",
    ]
    for name, label in SUBSETS.items():
        block = summary["subsets"][name]
        lines.extend(
            [
                f"## {label}（{block['images']} 张）",
                "",
                "| 方法 | 漏检 FNR | 水体误检 FPR | 两类全局 mIoU |",
                "|---|---:|---:|---:|",
            ]
        )
        for method in ("cnn_int8_variant", "cnn_int8", "forest_threshold_only", "forest_original", "udcp_otsu_rgb565"):
            m = block["methods"][method]
            lines.append(
                f"| {LABELS[method]} | {m['fnr']:.2%} | {m['water_false_positive_rate']:.2%} | {m['miou']:.4f} |"
            )
        delta = block["variant_vs_forest_71"]
        lines.extend(
            [
                "",
                f"相对推荐森林：漏检 {delta['fnr_percentage_points']:+.2f} 个百分点（95% 区间 {delta['fnr_ci95_pp'][0]:+.2f} ~ "
                f"{delta['fnr_ci95_pp'][1]:+.2f}），误检 {delta['fpr_percentage_points']:+.2f} 个百分点（{delta['fpr_ci95_pp'][0]:+.2f} ~ "
                f"{delta['fpr_ci95_pp'][1]:+.2f}）。",
                "",
            ]
        )
    rates = summary["strict_subset_class_rates"]
    lines.extend(
        [
            "## 最严格子集的逐类判为非水体比例",
            "",
            "水体一行是误检率，其余是召回率。",
            "",
            "| 类别 | 事后阈值版本 | 锁定阈值 | 森林阈值 71 |",
            "|---|---:|---:|---:|",
        ]
    )
    for name in CLASS_NAMES:
        lines.append(
            f"| {name} | {rates['cnn_int8_variant'][name]:.1%} | {rates['cnn_int8'][name]:.1%} | {rates['forest_threshold_only'][name]:.1%} |"
        )
    lines.extend(
        [
            "",
            "## 限制",
            "",
            "- 阈值是在看过 TEST 后选的；需要用新的数据（最好是 OV2640 实拍、按拍摄批次划分）确认。",
            "- int8 结果是 ESP-PPQ 对 ESP32-P4 的仿真；板上一致性由 water_seg_demo 的自检与参考掩膜比对确认。",
            "- 输出为水体/非水体分割，不是碰撞距离。",
            "",
        ]
    )
    (output / "RESULTS.md").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run", type=Path, default=RESULTS_DIR / "cnn_espdl_run_01")
    parser.add_argument("--baseline", type=Path, default=RESULTS_DIR / "evaluation_dedup")
    parser.add_argument("--fnr-cap", type=float, default=0.05)
    parser.add_argument("--output", type=Path, default=RESULTS_DIR / "cnn_espdl_run_01/threshold_cap5")
    args = parser.parse_args()
    run(args.run.resolve(), args.baseline.resolve(), args.fnr_cap, args.output.resolve())
